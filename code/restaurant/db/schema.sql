-- Các bảng dùng bởi module 1 và 2, chạy trong database đã chọn, không xóa dữ liệu.
CREATE TABLE IF NOT EXISTS tblStaff4 (
 id INTEGER(10) NOT NULL AUTO_INCREMENT PRIMARY KEY,
 fullName VARCHAR(255) NOT NULL, phoneNumber VARCHAR(255) NOT NULL,
 email VARCHAR(255) NOT NULL, workingStatus VARCHAR(50) NOT NULL,
 username VARCHAR(50) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL,
 accountStatus VARCHAR(50) NOT NULL, vaitro VARCHAR(50) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tblProduct4 (
 id INTEGER(10) NOT NULL AUTO_INCREMENT PRIMARY KEY,
 productCode VARCHAR(50) NOT NULL UNIQUE, name VARCHAR(255) NOT NULL,
 description VARCHAR(255) NULL, salePrice FLOAT(10) NOT NULL,
 image VARCHAR(255) NULL, saleStatus VARCHAR(50) NOT NULL,
 createdAt DATETIME NOT NULL, updatedAt DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tblDishCategory4 (
 id INTEGER(10) NOT NULL AUTO_INCREMENT PRIMARY KEY,
 categoryCode VARCHAR(50) NOT NULL UNIQUE, name VARCHAR(255) NOT NULL,
 description VARCHAR(255) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tblDish4 (
 tblDishCategory4id INTEGER(10) NOT NULL,
 tblProduct4id INTEGER(10) NOT NULL PRIMARY KEY,
 FOREIGN KEY (tblDishCategory4id) REFERENCES tblDishCategory4(id),
 FOREIGN KEY (tblProduct4id) REFERENCES tblProduct4(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- [NGOÀI THIẾT KẾ] Không tạo tblComboDish4 và tblServiceSession4 vì hai module không đọc hai bảng này.
CREATE TABLE IF NOT EXISTS tblCombo4 (
 startsAt DATETIME NOT NULL, endsAt DATETIME NOT NULL,
 tblProduct4id INTEGER(10) NOT NULL PRIMARY KEY,
 FOREIGN KEY (tblProduct4id) REFERENCES tblProduct4(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tblCustomer4 (
 id INTEGER(10) NOT NULL AUTO_INCREMENT PRIMARY KEY,
 customerCode VARCHAR(50) NOT NULL UNIQUE, fullName VARCHAR(255) NOT NULL,
 phoneNumber VARCHAR(255) NOT NULL, profileStatus VARCHAR(50) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tblMembershipCard4 (
 id INTEGER(10) NOT NULL AUTO_INCREMENT PRIMARY KEY,
 cardCode VARCHAR(50) NOT NULL UNIQUE, issuedAt DATE NOT NULL, status VARCHAR(50) NOT NULL,
 tblCustomer4id INTEGER(10) NOT NULL,
 FOREIGN KEY (tblCustomer4id) REFERENCES tblCustomer4(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tblOrder4 (
 id INTEGER(10) NOT NULL AUTO_INCREMENT PRIMARY KEY,
 orderCode VARCHAR(50) NOT NULL UNIQUE, createdAt DATETIME NOT NULL, status VARCHAR(50) NOT NULL,
 tblCustomer4id INTEGER(10) NULL,
 FOREIGN KEY (tblCustomer4id) REFERENCES tblCustomer4(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tblInvoice4 (
 id INTEGER(10) NOT NULL AUTO_INCREMENT PRIMARY KEY,
 invoiceCode VARCHAR(50) NOT NULL UNIQUE, issuedAt DATETIME NOT NULL,
 amountDue FLOAT(10) NOT NULL, paymentStatus VARCHAR(50) NOT NULL,
 tblOrder4id INTEGER(10) NOT NULL UNIQUE, tblStaff4id INTEGER(10) NOT NULL,
 FOREIGN KEY (tblOrder4id) REFERENCES tblOrder4(id), FOREIGN KEY (tblStaff4id) REFERENCES tblStaff4(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tblPayment4 (
 id INTEGER(10) NOT NULL AUTO_INCREMENT PRIMARY KEY,
 amount FLOAT(10) NOT NULL, method VARCHAR(50) NOT NULL, paidAt DATETIME NOT NULL, result VARCHAR(50) NOT NULL,
 tblInvoice4id INTEGER(10) NOT NULL, tblStaff4id INTEGER(10) NOT NULL,
 FOREIGN KEY (tblInvoice4id) REFERENCES tblInvoice4(id), FOREIGN KEY (tblStaff4id) REFERENCES tblStaff4(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tblOrderSubmission4 (
 id INTEGER(10) NOT NULL AUTO_INCREMENT PRIMARY KEY, submittedAt DATETIME NOT NULL,
 tblOrder4id INTEGER(10) NOT NULL, FOREIGN KEY (tblOrder4id) REFERENCES tblOrder4(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tblOrderSubmissionProduct4 (
 id INTEGER(10) NOT NULL AUTO_INCREMENT PRIMARY KEY,
 quantity INTEGER(10) NOT NULL, recordedUnitPrice FLOAT(10) NOT NULL,
 note VARCHAR(255) NULL, processingStatus VARCHAR(50) NOT NULL,
 processedAt DATETIME NULL, rejectionReason VARCHAR(255) NULL,
 tblOrderSubmission4id INTEGER(10) NOT NULL, tblProduct4id INTEGER(10) NOT NULL, tblStaff4id INTEGER(10) NOT NULL,
 FOREIGN KEY (tblOrderSubmission4id) REFERENCES tblOrderSubmission4(id),
 FOREIGN KEY (tblProduct4id) REFERENCES tblProduct4(id), FOREIGN KEY (tblStaff4id) REFERENCES tblStaff4(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
